"""Stratified train / valid / test split of the raw data.

Reads data/raw (never writes there) and saves train.csv, valid.csv and
test.csv to data/processed/. The split happens BEFORE any cleaning or
fitting, so nothing learned later can see valid or test rows.

    python -m scorecard.data.split
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

from scorecard.config import load_config, resolve_path
from scorecard.data.audit import md_table
from scorecard.data.load import PAST_DUE_COLUMNS, PAST_DUE_SPECIAL_CODES, TARGET, load_raw

# Lineage only: the row's position in cs-training.csv. Kept as the index (not a
# column) so no later step can accidentally use it as a feature.
ROW_ID = "row_id"
SPLIT_NAMES = ("train", "valid", "test")


def split_data(
    df: pd.DataFrame, *, valid_size: float, test_size: float, seed: int
) -> dict[str, pd.DataFrame]:
    """Split into train/valid/test, each keeping the overall bad rate.

    Two-stage split: first carve off test, then split the rest into train and
    valid. Sizes are shares of the WHOLE frame.
    """
    if not (0 < valid_size < 1 and 0 < test_size < 1 and valid_size + test_size < 1):
        raise ValueError(f"Bad split sizes: valid={valid_size}, test={test_size}")

    rest, test = train_test_split(df, test_size=test_size, stratify=df[TARGET], random_state=seed)
    # valid_size is a share of all rows, so rescale it to the rows left after test:
    # 0.15 / 0.85 = 17.6% of the remaining 85% = 15% of the whole.
    train, valid = train_test_split(
        rest,
        test_size=valid_size / (1 - test_size),
        stratify=rest[TARGET],
        random_state=seed,
    )
    # Sort by row_id so the saved files are stable and easy to diff.
    return {"train": train.sort_index(), "valid": valid.sort_index(), "test": test.sort_index()}


def split_summary(splits: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Rows, bad rate and number of 96/98-coded rows per split."""
    total = sum(len(s) for s in splits.values())
    rows = []
    for name, s in splits.items():
        coded = s[PAST_DUE_COLUMNS].isin(PAST_DUE_SPECIAL_CODES).any(axis=1)
        rows.append(
            {
                "split": name,
                "rows": len(s),
                "share": len(s) / total,
                "bads": int(s[TARGET].sum()),
                "bad_rate": s[TARGET].mean(),
                "coded_96_98_rows": int(coded.sum()),
            }
        )
    return pd.DataFrame(rows).set_index("split")


def save_splits(splits: dict[str, pd.DataFrame], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, frame in splits.items():
        frame.to_csv(out_dir / f"{name}.csv", index_label=ROW_ID)


def load_split(name: str, directory: Path | str | None = None) -> pd.DataFrame:
    """Read one saved split back, with row_id restored as the index."""
    if name not in SPLIT_NAMES:
        raise ValueError(f"Unknown split {name!r}; expected one of {SPLIT_NAMES}")
    if directory is None:
        directory = resolve_path(load_config()["data"]["processed_dir"])
    return pd.read_csv(Path(directory) / f"{name}.csv", index_col=ROW_ID)


def main() -> None:
    cfg = load_config()
    split_cfg = cfg["split"]
    df = load_raw()
    df.index.name = ROW_ID  # 0-based row number = Unnamed: 0 minus 1

    splits = split_data(
        df,
        valid_size=split_cfg["valid_size"],
        test_size=split_cfg["test_size"],
        seed=split_cfg["seed"],
    )
    out_dir = resolve_path(cfg["data"]["processed_dir"])
    save_splits(splits, out_dir)

    summary = split_summary(splits)
    report = resolve_path(cfg["reports"]["split_summary"])
    report.write_text(
        "# Split summary\n\n"
        f"Stratified on `{TARGET}`, seed {split_cfg['seed']}, sizes "
        f"{1 - split_cfg['valid_size'] - split_cfg['test_size']:.0%} / "
        f"{split_cfg['valid_size']:.0%} / {split_cfg['test_size']:.0%}. "
        "Generated by `python -m scorecard.data.split`.\n\n"
        + md_table(summary, pct_cols=["share", "bad_rate"])
        + "\n",
        encoding="utf-8",
    )
    print(f"Saved {', '.join(SPLIT_NAMES)} to {out_dir}; summary in {report}")


if __name__ == "__main__":
    main()

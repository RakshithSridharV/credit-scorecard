"""Apply the approved cleaning rules (D-003 to D-008) to each split.

Every rule is a fixed business rule, not a value learned from data, so the
same functions run on train, valid, test and, later, inside the scoring API
without leakage. Reads data/processed/, writes data/interim/.

    python -m scorecard.data.clean
"""

from __future__ import annotations

import pandas as pd

from scorecard.config import load_config, resolve_path
from scorecard.data.audit import md_table
from scorecard.data.load import FEATURES, PAST_DUE_COLUMNS, PAST_DUE_SPECIAL_CODES
from scorecard.data.split import ROW_ID, SPLIT_NAMES, load_split

INCOME = "MonthlyIncome"
DEBT_RATIO = "DebtRatio"
UTILISATION = "RevolvingUtilizationOfUnsecuredLines"
AGE = "age"

INCOME_PLACEHOLDERS = (0, 1)  # D-003: behave like "not reported", not "no income"
UTILISATION_MAX = 10  # D-007: above this, the value is a dollar balance, not a ratio
MIN_AGE = 18  # D-008: a credit contract needs an adult; age 0 is an entry error


def clean(df: pd.DataFrame) -> pd.DataFrame:
    """Turn placeholder and impossible values into NaN. Never drops rows.

    Works on a features-only frame (no target), so the API can reuse it.
    Returns a new frame; the input is not modified.
    """
    missing = set(FEATURES) - set(df.columns)
    if missing:
        raise ValueError(f"Cannot clean: missing columns {sorted(missing)}")

    out = df.copy()

    # Computed ONCE from the input, before any rule changes income. D-003 and
    # D-004 therefore use the same mask, and the result does not depend on rule order.
    income_unreported = df[INCOME].isna() | df[INCOME].isin(INCOME_PLACEHOLDERS)
    out[INCOME] = out[INCOME].mask(income_unreported)  # D-003
    out[DEBT_RATIO] = out[DEBT_RATIO].mask(income_unreported)  # D-004: dollars, not a ratio

    for col in PAST_DUE_COLUMNS:  # D-006: 96/98 are codes, not counts
        out[col] = out[col].mask(out[col].isin(PAST_DUE_SPECIAL_CODES))

    out[UTILISATION] = out[UTILISATION].mask(out[UTILISATION] > UTILISATION_MAX)  # D-007

    # D-005 (dependents) and D-010 (long tails) are deliberate "do nothing" rules.
    return out


def drop_invalid_rows(df: pd.DataFrame) -> pd.DataFrame:
    """Drop rows no model should ever score (D-008: age under 18).

    Kept apart from clean(): in training we drop such rows, but the API must
    reject them with an error instead, so it calls clean() and not this.
    """
    return df[df[AGE] >= MIN_AGE]


def nan_summary(before: pd.DataFrame, after: pd.DataFrame) -> pd.DataFrame:
    """NaN count per feature before and after cleaning one split."""
    t = pd.DataFrame(
        {"nan_before": before[FEATURES].isna().sum(), "nan_after": after[FEATURES].isna().sum()}
    )
    t["added"] = t["nan_after"] - t["nan_before"]
    t["share_after"] = t["nan_after"] / len(after)
    return t


def main() -> None:
    cfg = load_config()
    out_dir = resolve_path(cfg["data"]["interim_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)

    sections = []
    for name in SPLIT_NAMES:
        raw = load_split(name)
        cleaned = clean(drop_invalid_rows(raw))
        cleaned.to_csv(out_dir / f"{name}.csv", index_label=ROW_ID)

        summary = nan_summary(raw, cleaned)
        print(f"{name}: {len(raw):,} -> {len(cleaned):,} rows")
        print(summary.to_string(), "\n")
        sections.append(
            f"## {name}\n\nRows: {len(raw):,} before, {len(cleaned):,} after "
            f"({len(raw) - len(cleaned)} dropped by D-008).\n\n"
            + md_table(summary, pct_cols=["share_after"])
        )

    report = resolve_path(cfg["reports"]["clean_summary"])
    report.write_text(
        "# Cleaning summary\n\nRules D-003 to D-008 from `docs/decisions.md`. "
        "Generated by `python -m scorecard.data.clean`.\n\n" + "\n\n".join(sections) + "\n",
        encoding="utf-8",
    )
    print(f"Saved cleaned splits to {out_dir}; summary in {report}")


if __name__ == "__main__":
    main()

"""Performance by subgroup, for the model card (D-029).

A model can rank well overall and still fail one group: lower AUC (it separates
good from bad worse there), miscalibrated PDs (the group's risk is over- or
under-stated), or a much lower approval rate. This module reports all three for:

* age band, split at 62 because Regulation B gives applicants 62+ explicit
  protection (12 CFR 1002.6(b)(2));
* whether income was reported, because not reporting income is a choice an
  applicant makes (the income-withholding risk in D-023).

    python -m scorecard.evaluation.subgroups

Uses train-fitted artifacts and VALID data. Test was scored once (D-020) and is
not reopened for new analyses.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from numpy.typing import ArrayLike
from sklearn.metrics import roc_auc_score

from scorecard.config import load_config, resolve_path
from scorecard.data.audit import md_table
from scorecard.data.load import TARGET
from scorecard.data.split import load_split
from scorecard.evaluation.cutoff import economics_from_config, policy_cutoff
from scorecard.models.scorecard import Scorecard

AGE_EDGES = [-np.inf, 29, 44, 61, np.inf]
AGE_LABELS = ["18-29", "30-44", "45-61", "62+"]
MIN_CLASS = 30  # an AUC from fewer than 30 bads (or goods) is too noisy to report
FOUR_FIFTHS = 0.8  # Benchmark: adverse-impact screening rule of thumb (approval ratio)

PCT = ["share", "bad_rate", "mean_pd", "approval_rate", "bad_rate_approved", "goods_declined"]


def age_band(age: pd.Series) -> pd.Series:
    return pd.cut(age, bins=AGE_EDGES, labels=AGE_LABELS)


def income_status(income: pd.Series) -> pd.Series:
    # After clean(), missing covers both "not reported" and the 0/1 placeholders (D-003).
    return pd.Series(np.where(income.isna(), "not reported", "reported"), index=income.index)


def subgroup_table(
    groups: pd.Series, y: ArrayLike, pd_: ArrayLike, scores: ArrayLike, cutoff: int
) -> pd.DataFrame:
    """One row per group: size, risk, calibration, ranking and the decision outcome."""
    df = pd.DataFrame(
        {
            "g": np.asarray(groups),
            "y": np.asarray(y, dtype=int),
            "pd": np.asarray(pd_, dtype=float),
            "approved": np.asarray(scores) >= cutoff,  # same rule as the API
        }
    )
    rows: dict[str, dict[str, float]] = {}
    for name, d in df.groupby("g", observed=True, sort=False):
        bads, goods = int(d["y"].sum()), int((d["y"] == 0).sum())
        good_rows = d[d["y"] == 0]
        approved = d[d["approved"]]
        rows[str(name)] = {
            "rows": len(d),
            "share": len(d) / len(df),
            "bad_rate": d["y"].mean(),
            "mean_pd": d["pd"].mean(),
            "pd_to_bad_rate": d["pd"].mean() / d["y"].mean() if bads else np.nan,
            "auc": (roc_auc_score(d["y"], d["pd"]) if min(bads, goods) >= MIN_CLASS else np.nan),
            "approval_rate": d["approved"].mean(),
            "bad_rate_approved": approved["y"].mean() if len(approved) else np.nan,
            # Of the people who would have repaid, the share we turned away.
            "goods_declined": (~good_rows["approved"]).mean() if goods else np.nan,
        }
    table = pd.DataFrame(rows).T
    order = [g for g in AGE_LABELS + ["reported", "not reported"] if g in table.index]
    table = table.loc[order + [g for g in table.index if g not in order]]
    table["approval_ratio"] = table["approval_rate"] / table["approval_rate"].max()
    table["rows"] = table["rows"].astype(int)
    return table


def main() -> None:
    cfg = load_config()
    sc = Scorecard.from_json(resolve_path(cfg["artifacts"]["scorecard"]))
    cutoff = policy_cutoff(sc, economics_from_config(cfg))
    valid = load_split("valid", resolve_path(cfg["data"]["interim_dir"]))
    y, scores, pds = valid[TARGET], sc.score(valid), sc.score_pd(valid)

    by_age = subgroup_table(age_band(valid["age"]), y, pds, scores, cutoff)
    by_income = subgroup_table(income_status(valid["MonthlyIncome"]), y, pds, scores, cutoff)
    overall = subgroup_table(pd.Series("all", index=valid.index), y, pds, scores, cutoff)

    nl = "\n"
    sections = [
        "# Performance by subgroup" + nl,
        f"Train-fitted scorecard at the D-018 cutoff ({cutoff}); outcomes are **valid** "
        f"({len(valid):,} rows). Test is not reopened (D-020). "
        "Generated by `python -m scorecard.evaluation.subgroups`." + nl,
        "Columns: `pd_to_bad_rate` near 1 = calibrated for the group; `goods_declined` = share "
        "of applicants who repaid but would be declined; `approval_ratio` = group approval "
        f"rate / highest group's (**Benchmark:** below {FOUR_FIFTHS} flags possible adverse "
        "impact for review, the four-fifths rule of thumb). AUC is left blank when a group has "
        f"fewer than {MIN_CLASS} bads." + nl,
        "## All applicants" + nl,
        md_table(overall, pct_cols=PCT),
        nl + "## By age band" + nl,
        md_table(by_age, pct_cols=PCT),
        nl + "## By income reporting" + nl,
        md_table(by_income, pct_cols=PCT),
    ]
    report = resolve_path(cfg["reports"]["subgroups"])
    # newline="\n": the same bytes on every platform (D-027 line-ending risk).
    report.write_text(nl.join(sections) + nl, encoding="utf-8", newline="\n")

    pd.set_option("display.width", 200)
    print(by_age.round(4).to_string(), nl)
    print(by_income.round(4).to_string(), nl)
    print(f"Report: {report}")


if __name__ == "__main__":
    main()
